import assert from 'node:assert/strict';

export async function checkRecurrence({ click, fill, execute, until, sql, has, screenshot, clickText, openQuest, saveForm, stop, start, log }) {
  const dates = await execute('const fmt=d=>`${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,"0")}-${String(d.getDate()).padStart(2,"0")}`;return Array.from({length:6},(_,i)=>{const d=new Date();d.setDate(d.getDate()+i);return fmt(d)})');
  const [, tomorrow, day2, day3, day4] = dates;
  const normal = 'article[data-origin="recurring"][data-task-title="每日日语输入"]';
  const makeup = 'article[data-origin="makeup"][data-task-title="每日日语输入"]';
  const active = selector => execute('return document.querySelector(arguments[0])?.getAttribute("aria-pressed")==="true"', `${selector} button[aria-pressed]`);
  const qSql = query => sql(query.replaceAll('$QUEST', "(SELECT id FROM quests WHERE title='每日日语精读')"));
  async function select(selector, value) {
    await execute('const e=document.querySelector(arguments[0]);e.value=arguments[1];e.dispatchEvent(new Event("change",{bubbles:true}))', selector, value);
  }
  async function confirmRule() {
    await click('button[type="submit"]');
    await until(() => has('确认规则影响'), 'recurrence impact preview');
    await clickText('确认应用规则', 'dialog button');
    await until(async () => !await execute('return !!document.querySelector("aside[aria-label] form")'), 'rule committed');
  }
  await clickText('Quests目标与任务');
  await clickText('＋ 新建任务');
  await fill('input[aria-label="任务标题"]', '每日日语输入');
  await saveForm();
  await openQuest('每日日语输入');
  await clickText('设置重复规则');
  await select('select[aria-label="重复默认时段"]', 'evening');
  await fill('input[aria-label="重复开始时间"]', '19:00');
  await click('button[type="submit"]');
  await until(() => has('确认规则影响'), 'initial rule preview');
  assert.equal(await sql("SELECT count(*) FROM recurrence_versions;"), '0');
  await screenshot('phase-3-rule-preview');
  await clickText('确认应用规则', 'dialog button');
  await until(async () => !await execute('return !!document.querySelector("aside[aria-label] form")'), 'initial recurring conversion');
  await clickText('Today今日行动');
  await until(async () => !!await execute('return !!document.querySelector(arguments[0])', normal), 'normal Today instance');
  await click(`${normal} button[aria-label="记录进展：每日日语输入"]`);
  await fill('textarea[aria-label="执行说明"]', '完成第一段输入，保留原日期进展');
  await click('input[aria-label="确认执行内容"]');
  // The sidebar and row must share the same pending key, including before React rerenders.
  await execute('document.querySelector("aside form").requestSubmit();document.querySelector(arguments[0]).click()', `${normal} button[aria-pressed]`);
  await until(async () => !await execute('return !!document.querySelector("aside[aria-label] form")'), 'instance progress committed');
  assert.equal(await sql("SELECT count(*) FROM execution_records WHERE quest_id=(SELECT id FROM quests WHERE title='每日日语输入') AND kind='completion';"), '0');
  await click(`${normal} button[aria-label="查看「每日日语输入」详情"]`);
  await clickText('顺延或重新安排本次');
  assert.equal(await execute('return document.querySelector("input[aria-label=补做日期]").value'), tomorrow);
  await saveForm();
  await until(async () => await execute('return document.querySelector(arguments[0])?.dataset.disposition', normal) === 'rescheduled', 'original plan rescheduled');
  await fill('input[aria-label="查看日期"]', tomorrow);
  await until(async () => !!await execute('return !!document.querySelector(arguments[0]) && !!document.querySelector(arguments[1])', normal, makeup), 'normal plus explicit makeup');
  assert.equal(await sql("SELECT count(*) FROM plans WHERE quest_id=(SELECT id FROM quests WHERE title='每日日语输入') AND scheduled_on='" + tomorrow + "';"), '2');
  const ids = await execute('return [document.querySelector(arguments[0]).dataset.planId,document.querySelector(arguments[1]).dataset.planId]', normal, makeup);
  assert.notEqual(ids[0], ids[1]);
  await screenshot('phase-3-normal-and-makeup', normal);
  // Two different instances of the same Quest must not share a frontend pending key.
  await execute('document.querySelector(arguments[0]).click();document.querySelector(arguments[1]).click()', `${normal} button[aria-pressed]`, `${makeup} button[aria-pressed]`);
  await until(async () => await active(normal) && await active(makeup), 'same-Quest instances complete independently');
  await click(`${makeup} button[aria-pressed]`);
  await until(async () => !await active(makeup), 'undo makeup only');
  assert.equal(await active(normal), true);
  assert.equal(await sql("SELECT status FROM quests WHERE title='每日日语输入';"), 'open');
  assert.equal(await sql("SELECT count(*) FROM execution_records WHERE note='完成第一段输入，保留原日期进展';"), '1');
  log('explicit makeup remains separate; same-Quest instances complete concurrently and undo locally');

  await fill('input[aria-label="查看日期"]', day2);
  await until(async () => !!await execute('return !!document.querySelector(arguments[0])', normal), 'future normal instance');
  await click(`${normal} button[aria-label="查看「每日日语输入」详情"]`);
  await fill('input[aria-label="任务标题"]', '单次日语长阅读');
  await saveForm();
  assert.equal(await sql("SELECT title FROM quests WHERE id=(SELECT quest_id FROM plans WHERE id='" + ids[0] + "');"), '每日日语输入');
  await clickText('Quests目标与任务');
  await openQuest('每日日语输入');
  await clickText('编辑本次及未来');
  await fill('input[aria-label="重复生效日期"]', tomorrow);
  await fill('input[aria-label="重复任务标题"]', '每日日语精读');
  await select('select[aria-label="重复频率"]', 'interval');
  await fill('input[aria-label="间隔天数"]', '2');
  await click('button[type="submit"]');
  await until(() => has('确认规则影响'), 'future rule edit preview');
  assert.equal(await has(day2), true);
  assert.equal(await sql("SELECT count(*) FROM recurrence_versions;"), '1');
  await clickText('确认应用规则', 'dialog button');
  await until(async () => !await execute('return !!document.querySelector("aside[aria-label] form")'), 'future edit applied');
  assert.equal(await sql("SELECT json_extract(content_snapshot,'$.title') FROM plans WHERE id='" + ids[0] + "';"), '每日日语输入');
  assert.equal(await qSql("SELECT json_extract(content_snapshot,'$.title') FROM plans WHERE quest_id=$QUEST AND scheduled_on='" + day2 + "';"), '单次日语长阅读');
  await openQuest('每日日语精读');
  await clickText('选择已有实例');
  await fill('input[aria-label="实例日期"]', day4);
  await until(() => has('该日没有正常实例或已有补做安排'), 'non-rule date has no executable instance');
  assert.equal(await qSql("SELECT count(*) FROM plans WHERE quest_id=$QUEST AND scheduled_on='" + day4 + "';"), '0');
  await fill('input[aria-label="实例日期"]', tomorrow);
  await until(async () => await execute('return document.querySelectorAll("button[data-instance-id]").length') === 2, 'picker shows normal and makeup');
  await click('button[data-instance-id][data-origin="makeup"]');
  await until(() => has('仅本次详情'), 'off-page selected instance detail');
  assert.equal(await execute('return document.querySelector("input[aria-label=任务标题]").value'), '每日日语输入');
  await click('button[aria-label="关闭任务详情"]');
  await openQuest('每日日语精读');
  await clickText('选择已有实例');
  await fill('input[aria-label="实例日期"]', day3);
  await until(async () => await execute('return document.querySelectorAll("button[data-instance-id]").length') === 1, 'new interval occurrence generated');
  await click('button[aria-label="关闭任务详情"]');
  log('single override preserved outside the changed frequency; old snapshots and non-rule-date boundary hold');

  await openQuest('每日日语精读');
  await clickText('归档任务');
  await until(async () => !await execute('return !!document.querySelector("aside[aria-label] form")'), 'archive committed before navigation');
  await clickText('Today今日行动');
  await fill('input[aria-label="查看日期"]', tomorrow);
  await until(async () => !!await execute('return !!document.querySelector(arguments[0])', makeup), 'archived template keeps existing makeup');
  assert.equal(await execute('return !!document.querySelector(arguments[0])', normal), false);
  await click(`${makeup} button[aria-pressed]`);
  await until(() => active(makeup), 'archived-template makeup still executable');
  assert.equal(await qSql("SELECT count(*) FROM plans WHERE quest_id=$QUEST AND scheduled_on='" + day3 + "' AND disposition='active';"), '0');
  assert.equal(await qSql("SELECT count(*) FROM plans WHERE quest_id=$QUEST AND scheduled_on='" + day2 + "' AND disposition='active';"), '0');
  await clickText('Quests目标与任务');
  await select('select[aria-label="任务状态筛选"]', 'archived');
  await openQuest('每日日语精读');
  await clickText('恢复归档任务');
  await until(async () => !await execute('return !!document.querySelector("aside[aria-label] form")'), 'unarchive committed before filtering');
  await select('select[aria-label="任务状态筛选"]', 'active');
  await openQuest('每日日语精读');
  await clickText('选择已有实例');
  await fill('input[aria-label="实例日期"]', day3);
  await until(() => has('该日没有正常实例或已有补做安排'), 'unarchive does not restart rules');
  await click('button[aria-label="关闭任务详情"]');
  log('archive stops future normals and overrides, keeps makeup/history, and unarchive never auto-resumes');

  await clickText('＋ 新建任务');
  await fill('input[aria-label="任务标题"]', '每周运动');
  await saveForm();
  await openQuest('每周运动');
  await clickText('设置重复规则');
  await select('select[aria-label="重复频率"]', 'weekly');
  await click('input[aria-label="周三"]');
  await confirmRule();
  assert.equal(await sql("SELECT weekdays FROM recurrence_versions WHERE quest_id=(SELECT id FROM quests WHERE title='每周运动') AND effective_until IS NULL;"), '5');
  await openQuest('每周运动');
  await clickText('编辑本次及未来');
  await fill('input[aria-label="重复生效日期"]', tomorrow);
  await click('input[aria-label="启用重复规则"]');
  await confirmRule();
  assert.equal(await sql("SELECT enabled FROM recurrence_versions WHERE quest_id=(SELECT id FROM quests WHERE title='每周运动') AND effective_until IS NULL;"), '0');
  await stop();
  await start();
  await clickText('Quests目标与任务');
  await openQuest('每日日语精读');
  await clickText('选择已有实例');
  await fill('input[aria-label="实例日期"]', tomorrow);
  await until(async () => await execute('return document.querySelectorAll("button[data-instance-id]").length') === 2, 'recurring state restored after restart');
  assert.equal(await qSql("SELECT count(*) FROM execution_records WHERE quest_id=$QUEST AND kind='completion' AND revoked_at IS NULL AND completion_scope='instance';"), '2');
  assert.equal(await sql('PRAGMA integrity_check;'), 'ok');
  assert.equal(await sql('PRAGMA foreign_key_check;'), '');
  await click('button[aria-label="关闭任务详情"]');
  log('daily/weekly/interval rules, explicit pause and instance completion states survive restart');
  await clickText('Today今日行动');
}
