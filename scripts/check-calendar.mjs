import assert from 'node:assert/strict';

export async function checkCalendar({ click, fill, execute, until, sql, has, screenshot, clickText, openQuest, saveForm, stop, start, log }) {
  const [yesterday,today,tomorrow] = await execute('const fmt=d=>`${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,"0")}-${String(d.getDate()).padStart(2,"0")}`;return [-1,0,1].map(i=>{const d=new Date();d.setDate(d.getDate()+i);return fmt(d)})');
  const row = title => `article[data-plan-title="${title}"]`;
  const exists = selector => execute('return !!document.querySelector(arguments[0])', selector);
  async function action(title, label) { await clickText(label, `${row(title)} button`); }
  async function selectedDate(date, review = false) {
    await fill(`input[aria-label="${review ? '回顾日期' : '日历日期'}"]`, date);
    await until(() => exists(`[data-loaded-date="${date}"]`), 'date detail loaded');
    await until(async () => await execute('return document.querySelector(arguments[0])?.value', `input[aria-label="${review ? '回顾日期' : '日历日期'}"]`) === date, 'selected date');
  }
  async function progress(title, on, note) {
    await action(title,'记录进展');
    assert.equal(await execute('return document.querySelector("input[aria-label=实际发生日期]").value'),on);
    await fill('textarea[aria-label="执行说明"]',note);
    await click('input[aria-label="确认执行内容"]');
    await saveForm();
    await until(() => exists(row(title)), 'record and date refreshed');
  }
  await clickText('Today今日行动');
  assert.equal(await has('尚未标记回顾'),true);
  await clickText('回顾昨天');
  await until(() => has('回顾这一天'),'open yesterday review');
  assert.equal(await sql("SELECT count(*) FROM daily_reviews WHERE reviewed_at IS NOT NULL;"),'0');
  await clickText('Today今日行动');
  await clickText('今天暂不提示');
  await until(async () => !await has('尚未标记回顾'),'dismiss nonblocking reminder');
  assert.equal(await sql("SELECT reviewed_at IS NULL AND dismissed_on='"+today+"' FROM daily_reviews WHERE date='"+yesterday+"';"),'1');
  await stop(); await start();
  assert.equal(await has('尚未标记回顾'),false);
  log('yesterday reminder is optional, opening/closing is not review completion, dismissal survives restart');

  await clickText('Calendar日历与计划');
  await until(async () => await execute('return document.querySelectorAll("[data-calendar-date]").length')>=28,'real month calendar');
  await selectedDate(yesterday);
  await clickText('＋ 新建并安排');
  await fill('input[aria-label="任务标题"]','跨日技术文档');
  assert.equal(await execute('return document.querySelector("input[aria-label=安排日期]").value'),yesterday);
  await saveForm();
  await until(() => exists(row('跨日技术文档')),'new historical plan visible');
  await progress('跨日技术文档',yesterday,'昨日完成架构，保留原进展');
  const sourceId=await sql("SELECT id FROM plans WHERE quest_id=(SELECT id FROM quests WHERE title='跨日技术文档') AND scheduled_on='"+yesterday+"';");
  await selectedDate(today);
  await clickText('安排已有任务');
  await clickText('跨日技术文档','aside button');
  assert.equal(await execute('return document.querySelector("input[aria-label=安排日期]").value'),today);
  await fill('input[aria-label="开始时间"]','14:30');
  await fill('input[aria-label="结束时间"]','15:30');
  await saveForm();
  await until(() => exists(row('跨日技术文档')),'existing Quest planned into today');
  await progress('跨日技术文档',today,'目标安排原进展');
  const targetId=await sql("SELECT id FROM plans WHERE quest_id=(SELECT id FROM quests WHERE title='跨日技术文档') AND scheduled_on='"+today+"';");
  await clickText('Review每日回顾');
  await selectedDate(yesterday,true);
  await until(() => exists(row('跨日技术文档')),'source Review plan');
  await action('跨日技术文档','重新安排日期');
  await fill('input[aria-label="补做日期"]',today);
  await fill('input[aria-label="补做开始时间"]','19:00');
  await fill('input[aria-label="补做结束时间"]','20:00');
  await click('button[type="submit"]');
  await until(() => has('复用目标日已有安排'),'ordinary target reuse preview');
  assert.equal(await has('14:30'),true);
  await screenshot('phase-4-reschedule-preview');
  await sql("CREATE TRIGGER qa_phase4_fail BEFORE UPDATE OF next_plan_id ON plans BEGIN SELECT RAISE(ABORT,'QA phase4 failure'); END;");
  await clickText('确认重新安排','dialog button');
  await until(() => has('本次操作未保存'),'ordinary move rollback error');
  assert.equal(await sql("SELECT disposition FROM plans WHERE id='"+sourceId+"';"),'active');
  assert.equal(await sql("SELECT count(*) FROM plans WHERE quest_id=(SELECT id FROM quests WHERE title='跨日技术文档');"),'2');
  await sql('DROP TRIGGER qa_phase4_fail;');
  await click('button[type="submit"]');
  await until(() => has('复用目标日已有安排'),'retry preview');
  await clickText('确认重新安排','dialog button');
  await until(async () => !await exists('aside form'),'reschedule committed');
  assert.equal(await sql("SELECT next_plan_id FROM plans WHERE id='"+sourceId+"';"),targetId);
  assert.equal(await sql("SELECT start_time||'|'||end_time FROM plans WHERE id='"+targetId+"';"),'14:30|15:30');
  assert.equal(await sql("SELECT count(*) FROM execution_records WHERE note IN ('昨日完成架构，保留原进展','目标安排原进展');"),'2');
  await selectedDate(today,true);
  await until(() => exists(row('跨日技术文档')),'target Review plan');
  await action('跨日技术文档','记录完成');
  await fill('textarea[aria-label="执行说明"]','今日实际完成文档');
  await click('input[aria-label="确认执行内容"]');
  await saveForm();
  await until(() => exists(`${row('跨日技术文档')}[data-result=completed]`),'actual completion today');
  await selectedDate(yesterday,true);
  await until(() => exists(`${row('跨日技术文档')}[data-result=progressed][data-disposition=rescheduled]`),'yesterday progress and reschedule preserved');
  assert.equal(await exists(`${row('跨日技术文档')} [class*="contextActions"]`),false);
  assert.equal(await has('当前已完成，无需再次处理'),true);
  await screenshot('phase-4-history-review');
  await clickText('完成回顾');
  await until(() => has('已完成回顾'),'explicit review completion');
  assert.equal(await sql("SELECT reviewed_at IS NOT NULL FROM daily_reviews WHERE date='"+yesterday+"';"),'1');
  log('ordinary reschedule previews/reuses target times and progress, failure rolls back, completion stays on actual date');

  await clickText('Quests目标与任务');
  await clickText('＋ 新建任务');
  await fill('input[aria-label="任务标题"]','每日舒展');
  await saveForm();
  await openQuest('每日舒展');
  await clickText('设置重复规则');
  await click('button[type="submit"]');
  await until(() => has('确认规则影响'),'daily rule preview');
  await clickText('确认应用规则','dialog button');
  await until(async () => !await exists('aside form'),'daily rule committed');
  await clickText('Review每日回顾');
  await selectedDate(today,true);
  await until(() => exists(row('每日舒展')),'daily instance in Review');
  await progress('每日舒展',today,'舒展五分钟，独立进展保留');
  await action('每日舒展','放弃本次');
  await clickText('确认放弃本次','dialog button');
  await until(() => exists(`${row('每日舒展')}[data-disposition=skipped][data-result=progressed]`),'progress plus skipped state');
  assert.equal(await sql("SELECT status FROM quests WHERE title='每日舒展';"),'open');
  await clickText('＋ 新建并安排');
  await fill('input[aria-label="任务标题"]','尚未处理的下一步');
  await saveForm();
  await until(() => exists(row('尚未处理的下一步')),'an unprocessed plan remains before finishing Review');
  const openBefore=await sql("SELECT count(*) FROM plans p JOIN quests q ON q.id=p.quest_id WHERE p.scheduled_on='"+today+"' AND p.disposition='active' AND q.status='open';");
  assert.ok(Number(openBefore)>0);
  await clickText('完成回顾');
  await until(() => has('已完成回顾'),'today review can leave unprocessed items');
  assert.equal(await sql("SELECT count(*) FROM plans p JOIN quests q ON q.id=p.quest_id WHERE p.scheduled_on='"+today+"' AND p.disposition='active' AND q.status='open';"),openBefore);
  await sql("CREATE TRIGGER qa_month_fail BEFORE INSERT ON plans WHEN NEW.quest_id=(SELECT id FROM quests WHERE title='每日舒展') AND NEW.scheduled_on>'"+tomorrow+"' BEGIN SELECT RAISE(ABORT,'QA month generation failure'); END;");
  await clickText('规划明天');
  await until(() => exists('input[aria-label="日历日期"]'),'next-day planning in Calendar');
  assert.equal(await execute('return document.querySelector("input[aria-label=日历日期]").value'),tomorrow);
  await until(() => has('本次操作未保存'),'month generation failure is visible');
  await selectedDate(today);
  assert.equal(await has('本次操作未保存'),true,'selecting another date must not erase a failed month read');
  await sql('DROP TRIGGER qa_month_fail;');
  await clickText('重新读取');
  await until(async () => await execute('return document.querySelectorAll("[data-calendar-date]").length') >= 28,'month recovery after retry');
  await selectedDate(tomorrow);
  await until(() => exists(`${row('每日舒展')}[data-disposition=active]`),'next recurring instance unaffected');
  await clickText('＋ 新建并安排');
  await fill('input[aria-label="任务标题"]','明天推进下一步');
  assert.equal(await execute('return document.querySelector("input[aria-label=安排日期]").value'),tomorrow);
  await saveForm();
  await until(() => exists(row('明天推进下一步')),'new next-day ordinary plan');
  await screenshot('phase-4-calendar');
  await screenshot('phase-4-next-day',row('明天推进下一步'));
  await stop();await start();
  await clickText('Review每日回顾');
  await until(() => has('已完成回顾'),'review state restored');
  assert.equal(await sql("SELECT count(*) FROM execution_records WHERE note='舒展五分钟，独立进展保留';"),'1');
  assert.equal(await sql('PRAGMA integrity_check;'),'ok');
  assert.equal(await sql('PRAGMA foreign_key_check;'),'');
  log('Review preserves progress when skipping, allows unfinished items, plans tomorrow, and restores all states on restart');
  await clickText('Today今日行动');
}
